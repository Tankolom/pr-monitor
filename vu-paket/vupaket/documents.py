    doc = Document("01_Приказ_об_организации_воинского_учёта.docx", "Приказ об организации воинского учёта")
    b = doc.blocks
    b.append(("approval", [
        "СОГЛАСОВАНО",
        "Военный комиссар",
        d["commissariat"],
        "____________ / ______________",
        "«___» ____________ 20___ г.",
    ], []))
    b.append(_org_header(d))
    b.append(("title", "ПРИКАЗ"))
    b.append(("row2", "«___» ____________ 20___ г.", "№ ______"))
    b.append(("center", f"г. {d['city']}" if not d["city"].lower().startswith(("г.", "с.", "п.", "пгт")) else d["city"]))
    b.append(("h2", "Об организации воинского учёта"))
    b.append(("para", f"В соответствии с {LEGAL_BASIS}, в целях обеспечения исполнения гражданами воинской обязанности"))
    b.append(("h2", "ПРИКАЗЫВАЮ:"))
    items = [
        f"Организовать в {d['org_short']} ведение воинского учёта граждан, пребывающих в запасе, "
        "и граждан, подлежащих призыву на военную службу, из числа работающих.",
    ]
    if d["mode"] == "self":
        items.append("Обязанности по ведению воинского учёта оставляю за собой.")
    else:
        items.append(
            "Назначить ответственным за ведение воинского учёта (по совместительству, без освобождения "
            f"от основной работы): {name}, {pos.lower()}."
        )
    if d.get("deputy_name"):
        items.append(
            "На период временного отсутствия (отпуск, болезнь, командировка) работника, ведущего воинский учёт, "
            f"его обязанности исполняет: {d['deputy_name']}, {d['deputy_position'].lower()}."
        )
    items += [
        "Утвердить функциональные обязанности работника, осуществляющего воинский учёт (приложение № 1).",
        f"Утвердить План работы по ведению воинского учёта на {d['year']} год (приложение № 2) "
        "после его согласования с военным комиссариатом.",
        "Направлять в военный комиссариат сведения о принятых на работу (уволенных с работы) гражданах, "
        "состоящих либо обязанных состоять на воинском учёте, в течение 5 дней со дня приёма (увольнения), "
        "а сведения об изменении их семейного положения, образования, места работы, должности, места "
        f"жительства — в течение 5 дней со дня изменения, {_submit_phrase(d)}.",
        "Учётные документы (карточки по форме № 10) вести и хранить в порядке, определяемом "
        "Министерством обороны Российской Федерации, в условиях, исключающих доступ посторонних лиц.",
        "Контроль за исполнением настоящего приказа оставляю за собой.",
    ]
    for i, text in enumerate(items, 1):
        b.append(("item", f"{i}. {text}"))
    b.append(("spacer",))
    b.append(("sign", d["head_position"], initials(d["head_name"])))
    acquainted = []
    if d["mode"] == "appoint":
        acquainted.append(f"{pos} ____________ {initials(name)} «___» ________ 20___ г.")
    if d.get("deputy_name"):
        acquainted.append(f"{d['deputy_position']} ____________ {initials(d['deputy_name'])} «___» ________ 20___ г.")
    if acquainted:
        b.append(("spacer",))
        b.append(("h2", "С приказом ознакомлены:"))
        for line in acquainted:
            b.append(("plain", line))
    return doc


