def _fold(line: str) -> str:
    """Перенос строк iCalendar по 75 октетов (RFC 5545), не разрывая UTF-8."""
    out, cur = [], b""
    for ch in line:
        enc = ch.encode("utf-8")
        limit = 75 if not out else 74
        if len(cur) + len(enc) > limit:
            out.append(cur.decode("utf-8"))
            cur = b""
        cur += enc
    out.append(cur.decode("utf-8"))
    return "\r\n ".join(out)


def build_ics(d: dict, uid_seed: str) -> bytes:
    y = d["year"]
    m = d["sverka_month"]
    events = [
        (f"{y}{m:02d}10", "Воинский учёт: ежегодная сверка",
         "Сверить карточки ф. 10 с военными билетами работников и со сведениями военкомата (п. 32 «г», «д» Положения № 719)."),
        (f"{y}1115", "Воинский учёт: план на следующий год",
         "Подготовить План работы по ведению воинского учёта на следующий год."),
        (f"{y}1215", "Воинский учёт: согласовать план",
         "Согласовать План работы по ведению воинского учёта с военкоматом до 31 декабря."),
    ]
    lines = ["BEGIN:VCALENDAR", "VERSION:2.0", "PRODID:-//vu-paket//RU", "CALSCALE:GREGORIAN"]
    for i, (dt, summary, desc) in enumerate(events):
        lines += [
            "BEGIN:VEVENT",
            f"UID:{uid_seed}-{i}@vu-paket",
            "DTSTAMP:20260101T000000Z",
            f"DTSTART;VALUE=DATE:{dt}",
            "RRULE:FREQ=YEARLY",
            _fold(f"SUMMARY:{summary}"),
            _fold(f"DESCRIPTION:{desc}"),
            "BEGIN:VALARM",
            "TRIGGER:-P1D",
            "ACTION:DISPLAY",
            _fold(f"DESCRIPTION:{summary}"),
            "END:VALARM",
            "END:VEVENT",
        ]
    lines.append("END:VCALENDAR")
    return ("\r\n".join(lines) + "\r\n").encode("utf-8")


