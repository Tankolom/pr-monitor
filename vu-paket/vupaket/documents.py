def build_plan(d: dict) -> Document:
    y = d["year"]
    doc = Document(f"03_План_работы_по_воинскому_учёту_{y}.docx", f"План работы по ведению воинского учёта на {y} год")
    b = doc.blocks
    b.append(("right", ["Приложение № 2", f"к приказу {d['org_short']}", "от «___» ________ 20___ г. № ____"]))
    b.append(("approval", [
        "СОГЛАСОВАНО",
        "Военный комиссар",
        d["commissariat"],
        "____________ / ______________",
        "«___» ____________ 20___ г.",
    ], [
        "УТВЕРЖДАЮ",
        d["head_position"],
        d["org_short"],
        f"____________ {initials(d['head_name'])}",
        "«___» ____________ 20___ г.",
    ]))
    b.append(("title", "ПЛАН"))
    b.append(("center", f"работы по ведению воинского учёта в {d['org_short']} на {y} год"))
    rows = [[str(i), r[0], r[1], r[2], ""] for i, r in enumerate(plan_rows(d), 1)]
    b.append(("table", ["№ п/п", "Мероприятие", "Срок исполнения", "Исполнитель", "Отметка о выполнении"], rows, [1.0, 7.4, 3.6, 2.6, 2.4]))
    b.append(("spacer",))
    pos, name = _responsible(d)
    b.append(("sign", f"Ответственный за ведение воинского учёта, {pos.lower()}", initials(name)))
    return doc


