def build_letter(d: dict) -> Document:
    pos, name = _responsible(d)
    doc = Document("05_Письмо_в_военкомат_о_согласовании.docx", "Письмо в военкомат о согласовании документов")
    b = doc.blocks
    b.append(_org_header(d))
    if d.get("address"):
        b.append(("center", d["address"]))
    b.append(("spacer",))
    b.append(("row2", "Исх. № ______ от «___» ________ 20___ г.", ""))
    b.append(("right", ["Военному комиссару", d["commissariat"]]))
    b.append(("spacer",))
    b.append(("h2", "О согласовании документов по воинскому учёту"))
    b.append(("para",
              f"{d['org_short']} (ИНН {d['inn']}) направляет на согласование проект приказа «Об организации воинского учёта» "
              f"и План работы по ведению воинского учёта на {d['year']} год."))
    b.append(("para",
              f"Численность работников — {d['staff_total']} чел. Ответственный за ведение воинского учёта: "
              f"{name}, {pos.lower()}. Сведения о принятых и уволенных гражданах направляются {_submit_phrase(d)}."))
