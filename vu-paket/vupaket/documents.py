    b.append(("plain", "Приложения:"))
    b.append(("plain", "1. Проект приказа «Об организации воинского учёта» — на ___ л. в 1 экз."))
    b.append(("plain", f"2. План работы по ведению воинского учёта на {d['year']} год — на ___ л. в 1 экз."))
    b.append(("spacer",))
